#!/usr/bin/env python3
"""
Generalization confidence intervals (bootstrap, 95%) for held-out classes.
Data: skcw_mb512_semantic_results.jsonl — 72 per-video records (4 held-out dims × 18 × 1 seed).
Actually: 72 records across 18 dimensions, all class_id=28 (held-out).

Outputs: generalization_ci_summary.json + generalization_ci_table.tex
"""
import json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
FETCHED = os.path.join(HERE, "fetched")
OUT_DIR = os.path.join(HERE, "out")
os.makedirs(OUT_DIR, exist_ok=True)

rng = np.random.default_rng(seed=42)
N_BOOT = 10_000

with open(os.path.join(FETCHED, "skcw_mb512_semantic_results.jsonl"), encoding="utf-8") as f:
    recs = [json.loads(l) for l in f if l.strip()]

accs = np.array([r["det"]["msg_bit_acc"] for r in recs])
n = len(accs)

def bootstrap_ci(data, stat=np.mean, n_boot=N_BOOT, ci=0.95):
    boot = rng.choice(data, size=(n_boot, len(data)), replace=True)
    s = stat(boot, axis=1)
    lo = np.percentile(s, (1 - ci) / 2 * 100)
    hi = np.percentile(s, (1 + ci) / 2 * 100)
    return float(lo), float(hi), float(stat(data))

mean_lo, mean_hi, mean_val = bootstrap_ci(accs)
min_lo,  min_hi,  min_val  = bootstrap_ci(accs, stat=np.min)
std_lo,  std_hi,  std_val  = bootstrap_ci(accs, stat=np.std)

# Per-dimension breakdown
by_dim = {}
for r in recs:
    d = r["dimension"]
    by_dim.setdefault(d, []).append(r["det"]["msg_bit_acc"])

dim_stats = {}
for dim, vals in sorted(by_dim.items()):
    v = np.array(vals)
    lo, hi, m = bootstrap_ci(v) if len(v) >= 4 else (float(v.min()), float(v.max()), float(v.mean()))
    dim_stats[dim] = {"n": len(v), "mean": round(m, 4), "ci95_lo": round(lo, 4), "ci95_hi": round(hi, 4)}

# Training classes reference (from heldout_eval log)
train_ref_mean = 0.9996   # from heldout_eval_v6_last.json train_ref/strong/e_theta msg

summary = {
    "dataset": "HunyuanVideo T2V, held-out class_id=28, 512-bit, 18 dims × 4 videos=72",
    "n_videos": n,
    "overall_95ci": {
        "mean": round(mean_val, 4),
        "ci_lo": round(mean_lo, 4),
        "ci_hi": round(mean_hi, 4),
    },
    "min_95ci": {
        "min": round(min_val, 4),
        "ci_lo": round(min_lo, 4),
        "ci_hi": round(min_hi, 4),
    },
    "std_95ci": {
        "std": round(std_val, 4),
        "ci_lo": round(std_lo, 4),
        "ci_hi": round(std_hi, 4),
    },
    "train_test_gap": {
        "train_mean": train_ref_mean,
        "heldout_mean": round(mean_val, 4),
        "gap": round(train_ref_mean - mean_val, 4),
        "gap_pct": round((train_ref_mean - mean_val) * 100, 3),
    },
    "per_dimension": dim_stats,
    "n_bootstrap": N_BOOT,
}

with open(os.path.join(OUT_DIR, "generalization_ci_summary.json"), "w", encoding="utf-8") as f:
    json.dump(summary, f, indent=2, ensure_ascii=False)

# LaTeX table
rows = []
for dim, s in sorted(dim_stats.items(), key=lambda x: x[1]["mean"]):
    rows.append(f"{dim.replace('_', r'\_')} & {s['mean']:.4f} & [{s['ci95_lo']:.4f}, {s['ci95_hi']:.4f}] & {s['n']} \\\\")

tex = r"""% Auto-generated by generalization_ci.py
\begin{table}[!t]
\caption{Per-dimension held-out bit accuracy (class 28, 512-bit) with 95\% bootstrap CI.
Mean over 72 videos: @@MEAN@@ [@@LO@@, @@HI@@]; train--test gap @@GAP@@\% ($<0.1\%$).}
\label{tab:heldout_ci}
\centering
\footnotesize
\renewcommand{\arraystretch}{1.1}
\setlength{\tabcolsep}{5pt}
\begin{tabular}{lccr}
\toprule
Dimension & Mean & 95\% CI & $n$ \\
\midrule
@@ROWS@@
\midrule
Overall & @@MEAN@@ & [@@LO@@, @@HI@@] & 72 \\
\bottomrule
\end{tabular}
\end{table}
"""
tex = tex.replace("@@MEAN@@", f"{mean_val:.4f}")
tex = tex.replace("@@LO@@", f"{mean_lo:.4f}")
tex = tex.replace("@@HI@@", f"{mean_hi:.4f}")
tex = tex.replace("@@GAP@@", f"{(train_ref_mean - mean_val)*100:.3f}")
tex = tex.replace("@@ROWS@@", "\n".join(rows))

with open(os.path.join(OUT_DIR, "generalization_ci_table.tex"), "w", encoding="utf-8") as f:
    f.write(tex)

print(json.dumps({k: v for k, v in summary.items() if k != "per_dimension"}, indent=2, ensure_ascii=False))
print(f"\nPer-dimension ({len(dim_stats)} dims):")
for dim, s in sorted(dim_stats.items(), key=lambda x: x[1]["mean"]):
    print(f"  {dim:30s}  mean={s['mean']:.4f}  95%CI=[{s['ci95_lo']:.4f},{s['ci95_hi']:.4f}]")
print("\n[written] out/generalization_ci_summary.json")
print("[written] out/generalization_ci_table.tex")
